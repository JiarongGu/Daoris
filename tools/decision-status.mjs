/**
 * CONSOLIDATE1: the decisions' status, generated from the area documents' citations (`docs/decisions/README.md`).
 *
 *   node tools/decision-status.mjs   write the table: each decision live in the areas citing it, superseded, or history
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const areas = readdirSync('docs/areas').filter((f) => f.endsWith('.md') && f !== 'README.md');
const cited = new Map();
for (const f of areas) {
  const text = readFileSync(`docs/areas/${f}`, 'utf8');
  for (const m of text.matchAll(/\bD(\d{1,3})\b/g)) {
    const id = Number(m[1]);
    if (!cited.has(id)) cited.set(id, new Set());
    cited.get(id).add(f.replace(/\.md$/, ''));
  }
}
const superseded = new Set([30, 35, 81, 90, 92, 131, 136]);
const ids = readdirSync('docs/decisions').map((f) => /^D(\d+)\.md$/.exec(f)?.[1]).filter(Boolean).map(Number).sort((a, b) => a - b);
const title = (id) => readFileSync(`docs/decisions/D${id}.md`, 'utf8').split('\n')[0].replace(/^## D\d+ — /, '').replace(/\s*\(\d{4}-\d{2}-\d{2}\)\s*$/, '').replace(/\|/g, '/').slice(0, 110);
let rows = '', live = 0, sup = 0, hist = 0;
for (const id of ids) {
  const where = cited.get(id);
  const state = superseded.has(id) ? 'superseded' : where ? 'live' : 'history';
  if (state === 'live') live++; else if (state === 'superseded') sup++; else hist++;
  rows += `| D${id} | ${state} | ${where ? [...where].sort().join(', ') : ''} | ${title(id)} |\n`;
}
const head = `# Decisions: history, and where each one's rule lives now\n\nThe decisions are history. The current truth is in \`docs/areas/\`, one document per area, each rule ending with the decisions it\nreplaces. Read an area first; open a decision only for the reasoning behind a rule. A new decision is written only for a choice that\nrejected an alternative (\`change\`). This table is generated by \`node tools/decision-status.mjs\` from the areas' citations.\n\n- **live:** an area document states its rule (the areas named);\n- **superseded:** a later decision or the code replaced it whole;\n- **history:** no area cites it; its rule, if any, is carried by a later one.\n\n${live} live, ${sup} superseded, ${hist} history.\n\n| Decision | State | Areas | Title |\n|---|---|---|---|\n`;
writeFileSync('docs/decisions/README.md', head + rows);

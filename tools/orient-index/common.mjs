/** One read of each file, BOM-less and with LF endings, for every section that needs it. */
export function reader(root, files) {
  const cache = new Map();
  const known = new Set(files);
  const read = (path) => {
    if (!cache.has(path)) cache.set(path, readFileSync(join(root, path), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n'));
    return cache.get(path);
  };
  return { root, files, has: (path) => known.has(path), read, lines: (path) => read(path).split('\n') };
}


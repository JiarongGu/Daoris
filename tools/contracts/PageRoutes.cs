using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization.Metadata;
using Daoris.Desktop;
using Shenora.Core.Ipc;

namespace Daoris.ContractsGen;

/// <summary>
/// The page's TypeScript for the window's routes, read off the marks the desktop modules carry: every route the driver's module
/// answers, the payload record and answer of each handler that takes one, what each press declares it changes, the driver's and
/// the browser module's, and the catalogue key of each person's press, which every language words.
/// </summary>
public static class PageRoutes
{
    /// <summary>The file's text after its stamp line.</summary>
    public static string Write()
    {
        var text = new StringBuilder();
        text.Append("// Generated by tools/contracts.mjs from the window routes' marks in src/Daoris.Desktop/Daoris.Desktop.Modules; never edit by hand.\n");

        var payloads = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var answers = new PageTypes(Wire);
        var table = new StringBuilder();
        foreach (var shape in DriverModule.Shapes.Where(shape => shape.Payload is not null).OrderBy(shape => shape.Route, StringComparer.Ordinal))
        {
            var answer = shape.Answer is { } record ? answers.Ts(Ours(record)) : "unknown";
            table.Append($"  {Quoted(shape.Route)}: {{ payload: {Payload(Ours(shape.Payload!), payloads)}; answer: {answer} }};\n");
        }

        var declared = answers.Declarations.ToList();
        if (payloads.Keys.FirstOrDefault(name => declared.Any(each => each.StartsWith($"export type {name} =", StringComparison.Ordinal))) is { } twice)
        {
            throw new InvalidOperationException($"{twice} is a route's payload and a record an answer names; the page has one.");
        }

        foreach (var type in payloads.Values.Concat(declared)) text.Append('\n').Append(type).Append('\n');

        text.Append("\n/** Every route the driver's module answers. */\n");
        text.Append("export type DriverRoute =\n");
        text.Append(string.Join("\n", DriverModule.Routes.Order(StringComparer.Ordinal).Select(route => $"  | {Quoted(route)}"))).Append(";\n");

        text.Append("\n/** The driver's routes whose handler takes a payload record: the record its hook sends, and what it answers. */\n");
        text.Append("export type DriverPayloads = {\n").Append(table).Append("};\n");

        text.Append("\n/** What a press declares its answer changed: the scopes the page asks again, and the payload's field naming its session or what it is for. */\n");
        text.Append("export type Publishes = { readonly scopes: readonly string[]; readonly session?: string; readonly subject?: string };\n");
        text.Append("\n/** Each press's declaration by module and route, as the shell's publisher reads it; a read has none. */\n");
        text.Append("export const PUBLISHES: Readonly<Record<string, Readonly<Record<string, Publishes>>>> = {\n");
        foreach (var (module, routes) in new[] { (DriverModule.Name, DriverModule.Routes), (BrowserModule.Name, (IReadOnlyCollection<string>)BrowserModule.Presses) })
        {
            text.Append($"  {Quoted(module)}: {{\n");
            foreach (var route in routes.Order(StringComparer.Ordinal))
            {
                if (StatePublisher.Declared(new IpcRequest { Id = "page", Module = module, Type = route }) is not { Scopes: not StateScopes.None } change) continue;
                var scopes = string.Join(", ", StatePublisher.Names(change.Scopes).Select(Quoted));
                text.Append($"    {Quoted(route)}: {{ scopes: [{scopes}]{Field("session", change.Session)}{Field("subject", change.Subject)} }},\n");
            }

            text.Append("  },\n");
        }

        text.Append("};\n");

        // One key a line, with no trailing comma, so the names check reads the list as JSON with no TypeScript parser.
        var words = PipeCensus.Daoris.Routes
            .Where(route => route.Route is not null && (route.Class == PipeClass.Person || route.When?.Class == PipeClass.Person))
            .Select(route => PipeWording.Key(route.Module, route.Route!))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal);
        text.Append("\n/** The catalogue key of each person's press's act, which every language words (`scripts/names-check.mjs`). */\n");
        text.Append("export const PERSON_WORDS: readonly string[] = [\n");
        text.Append(string.Join(",\n", words.Select(key => $"  {JsonSerializer.Serialize(key)}"))).Append("\n];\n");
        return text.ToString();
    }

    /// <summary>The window's wire as an answer is written on it, read field by field through the serializer's own type info.</summary>
    private static readonly JsonSerializerOptions Wire = new(IpcJson.Options) { TypeInfoResolver = IpcJson.Options.TypeInfoResolver ?? new DefaultJsonTypeInfoResolver() };

    /// <summary>
    /// A payload record's type, each field as <see cref="RoutePayload"/> reads it: a required one as its kind, and the rest optional,
    /// since an absent text, number or yes or no is read as none and an absent flag as false.
    /// </summary>
    private static string Payload(Type record, IDictionary<string, string> declared)
    {
        if (!declared.ContainsKey(record.Name))
        {
            var fields = RoutePayload.Fields(record).Select(field => $"  {field.Name}{FieldType(field, declared)};").ToList();
            declared[record.Name] = fields.Count == 0
                ? $"export type {record.Name} = Record<string, never>;"
                : $"export type {record.Name} = {{\n{string.Join('\n', fields)}\n}};";
        }

        return record.Name;
    }

    private static string FieldType(PayloadField field, IDictionary<string, string> declared) => field.Read switch
    {
        PayloadRead.Required => field.Type == typeof(string) ? ": string" : field.Type == typeof(bool) ? ": boolean" : ": number",
        PayloadRead.Text => "?: string | null",
        PayloadRead.Flag => "?: boolean",
        PayloadRead.Choice => "?: boolean | null",
        PayloadRead.Number => "?: number | null",
        // A shape another reader owns, sent as written; absent and null are told apart.
        PayloadRead.Json => "?: unknown",
        PayloadRead.Records => $"?: {Payload(Ours(field.Item), declared)}[] | null",
        _ => "?: string[] | null",
    };

    /// <summary>A record the page is written from, declared in the desktop modules, whose sources the file's stamp reads.</summary>
    private static Type Ours(Type record) => record.Assembly == typeof(DriverModule).Assembly
        ? record
        : throw new InvalidOperationException($"{record.Name} is named by a window route and declared outside the desktop modules, which the page's stamp does not read.");

    private static string Field(string name, string? value) => value is null ? "" : $", {name}: {Quoted(value)}";

    /// <summary>A name as a TypeScript string; a name a quote or a backslash would break is refused, since no route is named so.</summary>
    private static string Quoted(string name) =>
        name.IndexOfAny(['\'', '\\', '\n', '\r']) < 0 ? $"'{name}'" : throw new InvalidOperationException($"`{name}` cannot be written as a page's name.");
}

using System.Text;
using System.Text.Json;
using Daoris.Desktop;
using Shenora.Core.Ipc;

namespace Daoris.ContractsGen;

/// <summary>
/// The page's TypeScript for the window's routes, read off the marks the desktop modules carry: every route the driver's module
/// answers, what each press declares it changes, the driver's and the browser module's, and the catalogue key of each person's
/// press, which every language words.
/// </summary>
public static class PageRoutes
{
    /// <summary>The file's text after its stamp line.</summary>
    public static string Write()
    {
        var text = new StringBuilder();
        text.Append("// Generated by tools/contracts.mjs from the window routes' marks in src/Daoris.Desktop/Daoris.Desktop.Modules; never edit by hand.\n");

        text.Append("\n/** Every route the driver's module answers. */\n");
        text.Append("export type DriverRoute =\n");
        text.Append(string.Join("\n", DriverModule.Routes.Order(StringComparer.Ordinal).Select(route => $"  | {Quoted(route)}"))).Append(";\n");

        text.Append("\n/** What a press declares its answer changed: the scopes the page asks again, and the payload's field naming its session or what it is for. */\n");
        text.Append("export type Publishes = { readonly scopes: readonly string[]; readonly session?: string; readonly subject?: string };\n");
        text.Append("\n/** Each press's declaration by module and route, as the shell's publisher reads it; a read has none. */\n");
        text.Append("export const PUBLISHES: Readonly<Record<string, Readonly<Record<string, Publishes>>>> = {\n");
        foreach (var (module, routes) in new[] { (DriverModule.Name, DriverModule.Routes), (BrowserModule.Name, (IReadOnlyCollection<string>)BrowserModule.Presses) })
        {
            text.Append($"  {Quoted(module)}: {{\n");
            foreach (var route in routes.Order(StringComparer.Ordinal))
            {
                if (StatePublisher.Declared(new IpcRequest { Id = "page", Module = module, Type = route }) is not { Scopes: not StateScopes.None } change) continue;
                var scopes = string.Join(", ", StatePublisher.Names(change.Scopes).Select(Quoted));
                text.Append($"    {Quoted(route)}: {{ scopes: [{scopes}]{Field("session", change.Session)}{Field("subject", change.Subject)} }},\n");
            }

            text.Append("  },\n");
        }

        text.Append("};\n");

        // One key a line, with no trailing comma, so the names check reads the list as JSON with no TypeScript parser.
        var words = PipeCensus.Daoris.Routes
            .Where(route => route.Route is not null && (route.Class == PipeClass.Person || route.When?.Class == PipeClass.Person))
            .Select(route => PipeWording.Key(route.Module, route.Route!))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal);
        text.Append("\n/** The catalogue key of each person's press's act, which every language words (`scripts/names-check.mjs`). */\n");
        text.Append("export const PERSON_WORDS: readonly string[] = [\n");
        text.Append(string.Join(",\n", words.Select(key => $"  {JsonSerializer.Serialize(key)}"))).Append("\n];\n");
        return text.ToString();
    }

    private static string Field(string name, string? value) => value is null ? "" : $", {name}: {Quoted(value)}";

    /// <summary>A name as a TypeScript string; a name a quote or a backslash would break is refused, since no route is named so.</summary>
    private static string Quoted(string name) =>
        name.IndexOfAny(['\'', '\\', '\n', '\r']) < 0 ? $"'{name}'" : throw new InvalidOperationException($"`{name}` cannot be written as a page's name.");
}

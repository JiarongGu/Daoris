using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization.Metadata;
using Daoris.Contracts;

namespace Daoris.ContractsGen;

/// <summary>
/// The page's TypeScript for the declared routes: each record a route names, read through its <see cref="JsonTypeInfo"/> so the
/// wire names and what may be absent are the serializer's own, and a <c>ROUTES</c> table of each route's method and path.
/// </summary>
/// <remarks>
/// A property that may be null is optional and may be null, since the wire leaves a null out; a request's property with a
/// default is optional, since the host reads its default where it is not sent. Everything else is required.
/// </remarks>
public sealed class PageTypes(JsonSerializerOptions wire)
{
    private readonly SortedDictionary<string, string?> _types = new(StringComparer.Ordinal);
    private readonly Dictionary<string, Type> _named = new(StringComparer.Ordinal);

    /// <summary>Each record declared so far, in name order.</summary>
    public IEnumerable<string> Declarations => _types.Values.OfType<string>();

    /// <summary>The file's text after its stamp line, for the routes <paramref name="routes"/> declare.</summary>
    public static string Write(IReadOnlyList<RouteDeclaration> routes)
    {
        var page = new PageTypes(ContractJson.Options);
        var table = new StringBuilder();
        var answers = new StringBuilder();
        foreach (var route in routes)
        {
            var request = page.Ts(route.Request);
            table.Append($"  {route.Request.Name}: {{ method: '{route.Method}', path: '{route.Path}' }},\n");
            answers.Append($"  {route.Request.Name}: {{ request: {request}; answer: {page.Ts(route.Answer)} }};\n");
        }

        var text = new StringBuilder();
        text.Append("// Generated by tools/contracts.mjs from the routes src/Daoris.Contracts declares; never edit by hand.\n");
        foreach (var declared in page.Declarations) text.Append('\n').Append(declared).Append('\n');
        text.Append("\n/** Each declared route's method and path, by its request record's name. */\n");
        text.Append("export const ROUTES = {\n").Append(table).Append("} as const;\n");
        text.Append("\n/** Each declared route's request and answer, by its request record's name. */\n");
        text.Append("export type Routes = {\n").Append(answers).Append("};\n");
        text.Append("\nexport type RouteName = keyof Routes;\n");
        return text.ToString();
    }

    /// <summary>The page's type for <paramref name="type"/> as <c>wire</c> writes it, each record it names declared.</summary>
    public string Ts(Type type)
    {
        if (Nullable.GetUnderlyingType(type) is { } inner) return Ts(inner);
        if (type == typeof(string) || type == typeof(DateTimeOffset) || type == typeof(DateTime) || type == typeof(Guid)) return "string";
        if (type == typeof(bool)) return "boolean";
        if (type.IsPrimitive || type == typeof(decimal)) return "number";
        if (type == typeof(object) || type == typeof(JsonElement) || typeof(JsonNode).IsAssignableFrom(type)) return "unknown";

        var info = wire.GetTypeInfo(type);
        return info.Kind switch
        {
            JsonTypeInfoKind.Enumerable => $"{Ts(info.ElementType!)}[]",
            JsonTypeInfoKind.Dictionary => $"Record<string, {Ts(info.ElementType!)}>",
            JsonTypeInfoKind.Object => Declare(type, info),
            _ => throw new InvalidOperationException($"{type.Name} has no page type: declare it as a record, a list, a map or a scalar."),
        };
    }

    private string Declare(Type type, JsonTypeInfo info)
    {
        if (_named.TryGetValue(type.Name, out var known))
        {
            if (known != type) throw new InvalidOperationException($"Two records are named {type.Name} ({known.FullName}, {type.FullName}); the page has one.");
            return type.Name;
        }

        _named[type.Name] = type;
        _types[type.Name] = null;
        var fields = info.Properties.Select(property =>
        {
            var nullable = property.IsGetNullable || Nullable.GetUnderlyingType(property.PropertyType) is not null;
            var optional = nullable || property.AssociatedParameter is { HasDefaultValue: true };
            return $"  {property.Name}{(optional ? "?" : "")}: {Ts(property.PropertyType)}{(nullable ? " | null" : "")};";
        }).ToList();
        _types[type.Name] = fields.Count == 0
            ? $"export type {type.Name} = Record<string, never>;"
            : $"export type {type.Name} = {{\n{string.Join('\n', fields)}\n}};";
        return type.Name;
    }
}
